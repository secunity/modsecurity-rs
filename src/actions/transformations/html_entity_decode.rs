/// Named-entity table for t:htmlEntityDecode: `(name, character)`.
///
/// Compared case-insensitively against the full extracted token; the length
/// must match exactly.  Prior implementations used strncasecmp() with the name
/// length only, which caused prefix collisions (e.g. "&ltest;" decoded to "<"
/// and dropped "est").  See GHSA-cxqf-vgrr-xxrv.
///
/// The contents below are generated, not hand-curated: a hand-written list
/// drifts from the specification (it is how &lcub;, &excl; and &Hat; came to
/// be missing while &caret;, &hyphen; and &tilde; were mapped to ASCII
/// characters the specification does not assign them).  Regenerate with
/// the C++ project's generator (`tools/gen-html-entities.py`, which emits
/// the C++ table; translate its output to the Rust array below):
///
/// ```text
/// curl -sSO https://html.spec.whatwg.org/entities.json
/// python3 tools/gen-html-entities.py entities.json
/// ```
///
/// Generated by tools/gen-html-entities.py from
/// https://html.spec.whatwg.org/entities.json -- do not edit by hand.
///
/// Every entity expanding to a single code point in U+0000..U+007F,
/// plus NBSP (U+00A0) and SOFT HYPHEN (U+00AD).  44 entries.
///
/// Case-insensitive matching collapses these spec distinctions:
///   &GT; = U+003E wins over &Gt; = U+226B
///   &LT; = U+003C wins over &Lt; = U+226A
///   &colon; = U+003A wins over &Colon; = U+2237
///   &verbar; = U+007C wins over &Verbar; = U+2016
///   &vert; = U+007C wins over &Vert; = U+2016
const NAMED_ENTITIES: &[(&[u8], u8)] = &[
    (b"amp", b'&'),
    (b"apos", b'\''),
    (b"ast", b'*'),
    (b"bsol", b'\\'),
    (b"colon", b':'),
    (b"comma", b','),
    (b"commat", b'@'),
    (b"diacriticalgrave", b'`'),
    (b"dollar", b'$'),
    (b"equals", b'='),
    (b"excl", b'!'),
    (b"grave", b'`'),
    (b"gt", b'>'),
    (b"hat", b'^'),
    (b"lbrace", b'{'),
    (b"lbrack", b'['),
    (b"lcub", b'{'),
    (b"lowbar", b'_'),
    (b"lpar", b'('),
    (b"lsqb", b'['),
    (b"lt", b'<'),
    (b"midast", b'*'),
    (b"nbsp", NBSP),
    (b"newline", b'\n'),
    (b"nonbreakingspace", NBSP),
    (b"num", b'#'),
    (b"percnt", b'%'),
    (b"period", b'.'),
    (b"plus", b'+'),
    (b"quest", b'?'),
    (b"quot", b'"'),
    (b"rbrace", b'}'),
    (b"rbrack", b']'),
    (b"rcub", b'}'),
    (b"rpar", b')'),
    (b"rsqb", b']'),
    (b"semi", b';'),
    (b"shy", 0xAD),
    (b"sol", b'/'),
    (b"tab", b'\t'),
    (b"underbar", b'_'),
    (b"verbar", b'|'),
    (b"vert", b'|'),
    (b"verticalline", b'|'),
];

fn lookup_named_entity(name: &[u8]) -> Option<u8> {
    NAMED_ENTITIES.iter().find(|(n, _)| n.len() == name.len() && n.eq_ignore_ascii_case(name)).map(|&(_, ch)| ch)
}

/// `(unsigned char)strtol(digits, nullptr, base)` for a non-empty run of
/// valid digits: strtol saturates at LONG_MAX on overflow.
fn strtol_to_byte(digits: &[u8], base: u32) -> u8 {
    let mut acc: i64 = 0;
    for &c in digits {
        let v = i64::from((c as char).to_digit(base).unwrap_or(0));
        match acc.checked_mul(i64::from(base)).and_then(|a| a.checked_add(v)) {
            Some(a) => acc = a,
            None => {
                acc = i64::MAX;
                break;
            }
        }
    }
    acc as u8
}

fn inplace(input: &mut Vec<u8>) -> bool {
    let input_len = input.len();
    let mut d = 0usize;
    let mut i = 0usize;

    'outer: while i < input_len {
        let mut copy = 1usize;

        // Require an ampersand and at least one character to
        // start looking into the entity.
        'entity: {
            if input[i] == b'&' && i + 1 < input_len {
                let mut j = i + 1;

                if input[j] == b'#' {
                    // Numerical entity.
                    copy += 1;

                    if j + 1 >= input_len {
                        break 'entity; // Not enough bytes.
                    }
                    j += 1;

                    let (base, k) = if input[j] == b'x' || input[j] == b'X' {
                        // Hexadecimal entity.
                        copy += 1;

                        if j + 1 >= input_len {
                            break 'entity; // Not enough bytes.
                        }
                        j += 1; // j is the position of the first digit now.

                        let k = j;
                        while j < input_len && input[j].is_ascii_hexdigit() {
                            j += 1;
                        }
                        (16, k)
                    } else {
                        // Decimal entity.
                        let k = j;
                        while j < input_len && input[j].is_ascii_digit() {
                            j += 1;
                        }
                        (10, k)
                    };

                    if j > k {
                        // Do we have at least one digit?
                        // Decode the entity.
                        input[d] = strtol_to_byte(&input[k..j], base);
                        d += 1;

                        // Skip over the semicolon if it's there.
                        i = if j < input_len && input[j] == b';' { j + 1 } else { j };
                        continue 'outer;
                    }
                    break 'entity;
                } else {
                    // Text entity.
                    let k = j;
                    while j < input_len && input[j].is_ascii_alphanumeric() {
                        j += 1;
                    }
                    if j > k {
                        // Do we have at least one character?
                        let Some(decoded) = lookup_named_entity(&input[k..j]) else {
                            // Unknown entity: copy the raw data over.
                            copy = j - k + 1;
                            break 'entity;
                        };
                        input[d] = decoded;
                        d += 1;

                        // Skip over the semicolon if it's there.
                        i = if j < input_len && input[j] == b';' { j + 1 } else { j };
                        continue 'outer;
                    }
                }
            }
        }

        // HTML_ENT_OUT:
        for _ in 0..copy {
            input[d] = input[i];
            d += 1;
            i += 1;
        }
    }

    let changed = d != input_len;
    input.truncate(d);
    changed
}

impl Transformation for HtmlEntityDecode {
    fn transform(&self, value: &mut Vec<u8>, _t: Option<&Transaction<'_>>) -> bool {
        inplace(value)
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn run(input: &[u8]) -> (Vec<u8>, bool) {
        let mut v = input.to_vec();
        let changed = inplace(&mut v);
        (v, changed)
    }

    #[test]
    fn decodes() {
        assert_eq!(run(b"&lt;&#65;&#x42&LT"), (b"<AB<".to_vec(), true));
        assert_eq!(run(b"&ltest;"), (b"&ltest;".to_vec(), false));
        assert_eq!(run(b"&#;&#x;&"), (b"&#;&#x;&".to_vec(), false));
        assert_eq!(run(b"&nbsp;"), (vec![NBSP], true));
        // strtol saturates at LONG_MAX -> 0xff
        assert_eq!(run(b"&#99999999999999999999999;"), (vec![0xff], true));
        assert_eq!(run(b"&#x1ffffffffffffffff;"), (vec![0xff], true));
        assert_eq!(run(b"&#321;"), (vec![321u32 as u8], true));
    }
}
